CREATE OR REPLACE FUNCTION public.delete_my_product_review(p_review_id bigint) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  DELETE FROM public.product_reviews WHERE id = p_review_id AND customer_id = auth.uid();
  IF NOT FOUND THEN RAISE EXCEPTION 'Review not found'; END IF;
END; $$;

