CREATE OR REPLACE FUNCTION public.set_product_review_visibility(p_review_id bigint, p_is_hidden boolean) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF lower(coalesce(auth.jwt() ->> 'email', '')) <> 'muhammadhassanattari450@gmail.com' THEN
    RAISE EXCEPTION 'Owner access required';
  END IF;
  UPDATE public.product_reviews SET is_hidden = p_is_hidden, updated_at = now() WHERE id = p_review_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Review not found'; END IF;
