-- Food World customer reviews. Run after pos_migration.sql in Supabase SQL Editor.
-- Ratings are written only through submit_product_review(), never directly from the browser.

ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS customer_id uuid REFERENCES auth.users(id);
CREATE INDEX IF NOT EXISTS orders_customer_id_idx ON public.orders(customer_id);

CREATE TABLE IF NOT EXISTS public.product_reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  customer_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  review text CHECK (char_length(review) <= 500),
  customer_name text NOT NULL DEFAULT 'Verified customer',
  is_hidden boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (customer_id, product_id, order_id)
);

CREATE INDEX IF NOT EXISTS product_reviews_product_visible_idx
  ON public.product_reviews(product_id) WHERE is_hidden = false;

ALTER TABLE public.product_reviews ENABLE ROW LEVEL SECURITY;
-- Read access deliberately exposes only the safe display fields through the view below.
CREATE OR REPLACE VIEW public.product_review_feed AS
  SELECT id, product_id, rating, review, customer_name, created_at
  FROM public.product_reviews WHERE is_hidden = false;

CREATE OR REPLACE VIEW public.product_rating_summary AS
  SELECT product_id, round(avg(rating)::numeric, 1) AS average_rating, count(*)::int AS review_count,
    count(*) FILTER (WHERE rating = 5)::int AS five_star,
    count(*) FILTER (WHERE rating = 4)::int AS four_star,
    count(*) FILTER (WHERE rating = 3)::int AS three_star,
    count(*) FILTER (WHERE rating = 2)::int AS two_star,
    count(*) FILTER (WHERE rating = 1)::int AS one_star
  FROM public.product_reviews WHERE is_hidden = false GROUP BY product_id;

-- Only safe public views may be selected. Direct table writes/reads are denied.
DROP POLICY IF EXISTS "public read visible product reviews" ON public.product_reviews;

CREATE OR REPLACE FUNCTION public.submit_product_review(
  p_product_id bigint, p_order_id bigint, p_rating smallint, p_review text DEFAULT NULL
) RETURNS public.product_reviews
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_order public.orders; v_result public.product_reviews; v_items jsonb;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Please sign in to review a purchase'; END IF;
  IF p_rating NOT BETWEEN 1 AND 5 THEN RAISE EXCEPTION 'Rating must be between 1 and 5'; END IF;
  SELECT * INTO v_order FROM public.orders WHERE id = p_order_id AND customer_id = auth.uid();
  IF NOT FOUND THEN RAISE EXCEPTION 'This order does not belong to the signed-in customer'; END IF;
  IF lower(coalesce(v_order.status, 'pending')) NOT IN ('completed', 'delivered') THEN
    RAISE EXCEPTION 'Only completed orders can be reviewed';
  END IF;
  v_items := CASE WHEN jsonb_typeof(v_order.items) = 'object' THEN coalesce(v_order.items->'items', '[]'::jsonb) ELSE v_order.items END;
  IF jsonb_typeof(v_items) <> 'array' OR NOT EXISTS (
    SELECT 1 FROM jsonb_array_elements(v_items) item
    WHERE coalesce(item->>'id', item->>'product_id') ~ '^\\d+$'
      AND coalesce(item->>'id', item->>'product_id')::bigint = p_product_id
  ) THEN RAISE EXCEPTION 'This product was not purchased in the selected order'; END IF;
  INSERT INTO public.product_reviews(product_id, customer_id, order_id, rating, review, customer_name)
  VALUES (p_product_id, auth.uid(), p_order_id, p_rating, nullif(trim(p_review), ''),
    coalesce(nullif(trim(v_order.customer_name), ''), 'Verified customer'))
  ON CONFLICT (customer_id, product_id, order_id) DO UPDATE SET
    rating = excluded.rating, review = excluded.review, updated_at = now()
  RETURNING * INTO v_result;
  RETURN v_result;
END; $$;

CREATE OR REPLACE FUNCTION public.get_my_order_reviews(p_order_id bigint)
RETURNS SETOF public.product_reviews
LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  SELECT * FROM public.product_reviews WHERE order_id = p_order_id AND customer_id = auth.uid();
$$;

