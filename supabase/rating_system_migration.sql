-- FOOD WORLD — CUSTOMER PRODUCT RATING SYSTEM
-- Run this in: Supabase Dashboard > SQL Editor > New Query > Run
-- This is SEPARATE from product_reviews (which requires order_id).
-- This table allows ANY authenticated customer to rate a product.
-- ================================================================

-- ----------------------------------------------------------------
-- 1. Create the product_ratings table
-- ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.product_ratings (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id    bigint        NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  customer_id   uuid          NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  rating        smallint      NOT NULL CHECK (rating BETWEEN 1 AND 5),
  created_at    timestamptz   NOT NULL DEFAULT now(),
  updated_at    timestamptz   NOT NULL DEFAULT now(),
  -- One rating per customer per product (UPSERT pattern)
  UNIQUE (customer_id, product_id)
);

CREATE INDEX IF NOT EXISTS product_ratings_product_id_idx ON public.product_ratings (product_id);
CREATE INDEX IF NOT EXISTS product_ratings_customer_id_idx ON public.product_ratings (customer_id);

-- ----------------------------------------------------------------
-- 2. Enable Row Level Security
-- ----------------------------------------------------------------
ALTER TABLE public.product_ratings ENABLE ROW LEVEL SECURITY;

-- Drop old policies if re-running this migration
DROP POLICY IF EXISTS "customers_select_ratings"    ON public.product_ratings;
DROP POLICY IF EXISTS "customers_insert_own_rating" ON public.product_ratings;
DROP POLICY IF EXISTS "customers_update_own_rating" ON public.product_ratings;
DROP POLICY IF EXISTS "customers_delete_own_rating" ON public.product_ratings;

-- Anyone (including anonymous) can read ratings (needed for product cards)
CREATE POLICY "customers_select_ratings"
  ON public.product_ratings
  FOR SELECT
  USING (true);

-- Authenticated customers can insert ONLY their own rating
CREATE POLICY "customers_insert_own_rating"
  ON public.product_ratings
  FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = customer_id);

-- Authenticated customers can update ONLY their own rating
CREATE POLICY "customers_update_own_rating"
  ON public.product_ratings
  FOR UPDATE
  TO authenticated
  USING (auth.uid() = customer_id)
  WITH CHECK (auth.uid() = customer_id);

-- Authenticated customers can delete ONLY their own rating
CREATE POLICY "customers_delete_own_rating"
  ON public.product_ratings
  FOR DELETE
  TO authenticated
  USING (auth.uid() = customer_id);

-- ----------------------------------------------------------------
-- 3. Auto-update the updated_at timestamp
-- ----------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.update_product_rating_timestamp()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS set_product_rating_updated_at ON public.product_ratings;
CREATE TRIGGER set_product_rating_updated_at
  BEFORE UPDATE ON public.product_ratings
  FOR EACH ROW EXECUTE FUNCTION public.update_product_rating_timestamp();

-- ----------------------------------------------------------------
-- 4. Per-product rating summary view (used by ProductCard & filter)
-- ----------------------------------------------------------------
CREATE OR REPLACE VIEW public.product_ratings_summary AS
  SELECT
    product_id,
    ROUND(AVG(rating)::numeric, 1)  AS avg_rating,
    COUNT(*)::int                   AS rating_count
  FROM public.product_ratings
  GROUP BY product_id;

-- ----------------------------------------------------------------
-- 5. Grant access to views
-- ----------------------------------------------------------------
GRANT SELECT ON public.product_ratings_summary TO anon, authenticated;
GRANT SELECT ON public.product_ratings TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.product_ratings TO authenticated;

